#!/usr/bin/env python3
"""Design and simulate the digital filters of the stethoscope.

* Designs the 16 kHz -> 4 kHz anti-aliasing FIR and writes it to
  firmware/stethoscope/src/dsp/fir_decim_coeffs.h (the firmware includes it).
* Plots the magnitude / phase / group delay of every listening mode, the mains
  notch, the heart-rate band and the decimation filter (PNG files for the
  report / presentation).
* Runs the complete pipeline on a synthetic heart-sound signal to show raw vs.
  filtered output and the heart-rate estimate.

Usage:
    python design_filters.py                 # write header + plots to ./filter_design/
    python design_filters.py --header-only   # only regenerate the C header
"""
from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
from scipy import signal

from stetho import dsp
from stetho.synth import synth_pcg, to_adc_codes

ROOT = Path(__file__).resolve().parents[1]
HEADER = ROOT / "stethoscope" / "src" / "dsp" / "fir_decim_coeffs.h"


def write_header(taps: np.ndarray) -> None:
    w, h = signal.freqz(taps, worN=8192, fs=dsp.FS_ADC)
    db = 20 * np.log10(np.maximum(np.abs(h), 1e-12))
    pass_ripple = np.ptp(db[w <= 1000])
    stop_att = -np.max(db[w >= dsp.FS_ADC / dsp.DECIMATION / 2])
    lines = [
        "// AUTO-GENERATED by firmware/tools/design_filters.py - do not edit by hand.",
        "//",
        f"// Anti-aliasing FIR for decimation {dsp.FS_ADC} Hz -> {dsp.FS} Hz (factor {dsp.DECIMATION}).",
        f"// Kaiser window (beta={dsp.DECIM_KAISER_BETA}), {len(taps)} taps, cutoff {dsp.DECIM_CUTOFF_HZ:.0f} Hz.",
        f"// Passband ripple 0-1000 Hz: {pass_ripple:.3f} dB; attenuation >= {dsp.FS // 2} Hz: {stop_att:.1f} dB.",
        f"// Group delay: {(len(taps) - 1) / 2:.1f} samples = {(len(taps) - 1) / 2 / dsp.FS_ADC * 1e3:.2f} ms.",
        "#pragma once",
        "",
        f"#define FIR_DECIM_NUM_TAPS {len(taps)}",
        "",
        "static const float kFirDecimTaps[FIR_DECIM_NUM_TAPS] = {",
    ]
    for i in range(0, len(taps), 4):
        lines.append("    " + " ".join(f"{t: .9e}f," for t in taps[i:i + 4]))
    lines += ["};", ""]
    HEADER.write_text("\n".join(lines))
    print(f"wrote {HEADER.relative_to(ROOT.parent)}  ripple={pass_ripple:.3f} dB  stop={stop_att:.1f} dB")


def plot_all(out: Path) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    out.mkdir(parents=True, exist_ok=True)
    fs = dsp.FS

    # 1) Listening modes
    fig, ax = plt.subplots(2, 1, figsize=(9, 7), sharex=True)
    f = np.logspace(0, np.log10(fs / 2 * 0.999), 3000)
    for mode in ["heart", "bell", "diaphragm", "wide"]:
        sos = dsp.user_chain_sos(mode, notch_hz=50.0)
        _, h = signal.sosfreqz(sos, worN=f, fs=fs)
        lo, hi = dsp.MODES[mode]
        ax[0].semilogx(f, 20 * np.log10(np.abs(h) + 1e-12), label=f"{mode} ({lo:.0f}-{hi:.0f} Hz)")
        w, gd = signal.group_delay((signal.sos2tf(sos)), w=f, fs=fs)
        ax[1].semilogx(f, gd / fs * 1e3, label=mode)
    ax[0].set_ylim(-80, 5)
    ax[0].set_ylabel("Magnitude (dB)")
    ax[0].set_title("Listening-mode filters (4th-order Butterworth HP+LP, 50 Hz notch Q=30), fs = 4 kHz")
    ax[0].grid(True, which="both", alpha=0.3)
    ax[0].legend()
    ax[1].set_ylim(0, 40)
    ax[1].set_ylabel("Group delay (ms)")
    ax[1].set_xlabel("Frequency (Hz)")
    ax[1].grid(True, which="both", alpha=0.3)
    fig.tight_layout()
    fig.savefig(out / "modes_response.png", dpi=150)
    plt.close(fig)

    # 2) Decimation FIR + analog AFE
    taps = dsp.decimation_taps()
    w, h = signal.freqz(taps, worN=8192, fs=dsp.FS_ADC)
    fig, ax = plt.subplots(figsize=(9, 4))
    ax.plot(w, 20 * np.log10(np.abs(h) + 1e-12), label="decimation FIR (digital)")
    afe = signal.butter(2, 1600, analog=True)
    wa, ha = signal.freqs(*afe, worN=2 * np.pi * np.maximum(w, 1))
    ax.plot(w, 20 * np.log10(np.abs(ha) + 1e-12), "--", label="AFE Sallen-Key LPF ~1.6 kHz (model)")
    ax.axvline(dsp.FS / 2, color="k", lw=0.8, ls=":")
    ax.text(dsp.FS / 2, -20, " new Nyquist (2 kHz)")
    ax.set_ylim(-100, 5)
    ax.set_xlabel("Frequency (Hz)")
    ax.set_ylabel("Magnitude (dB)")
    ax.set_title(f"Anti-aliasing: {len(taps)}-tap FIR, 16 kHz -> 4 kHz")
    ax.grid(True, alpha=0.3)
    ax.legend()
    fig.tight_layout()
    fig.savefig(out / "decimation_fir.png", dpi=150)
    plt.close(fig)

    # 3) Notch + HR band
    fig, ax = plt.subplots(figsize=(9, 4))
    f = np.linspace(1, 400, 4000)
    _, h = signal.sosfreqz(dsp.notch_sos(fs, 50.0), worN=f, fs=fs)
    ax.plot(f, 20 * np.log10(np.abs(h) + 1e-12), label="mains notch 50 Hz, Q=30")
    _, h = signal.sosfreqz(dsp.hr_chain_sos(50.0), worN=f, fs=fs)
    ax.plot(f, 20 * np.log10(np.abs(h) + 1e-12), label="HR band 25-150 Hz (+notch)")
    ax.set_ylim(-60, 5)
    ax.set_xlabel("Frequency (Hz)")
    ax.set_ylabel("Magnitude (dB)")
    ax.grid(True, alpha=0.3)
    ax.legend()
    fig.tight_layout()
    fig.savefig(out / "notch_hr_band.png", dpi=150)
    plt.close(fig)

    # 4) Pipeline demo on synthetic PCG with hum + noise
    x, s1 = synth_pcg(duration_s=20, fs=4000, bpm=75, snr_db=10, hum_hz=50, hum_rel=1.0, seed=3)
    codes = to_adc_codes(x * 0.5, 4000)
    res = dsp.run_pipeline(dsp.adc_to_float(codes), mode="heart")
    t = np.arange(len(res.raw)) / fs
    tt, bpm, conf, valid = dsp.hr_track(res.raw)
    fig, ax = plt.subplots(3, 1, figsize=(10, 8))
    sl = (t > 10) & (t < 14)
    ax[0].plot(t[sl], res.raw[sl], lw=0.6)
    ax[0].set_title("Raw (decimated, DC removed): heart sounds + noise + 50 Hz hum")
    ax[1].plot(t[sl], res.filtered[sl], lw=0.6, color="C1")
    ax[1].set_title("Filtered: 'heart' mode (50 Hz notch + 25-400 Hz band-pass)")
    ax[2].plot(tt, bpm, ".-", label="estimated HR")
    ax[2].axhline(75, color="k", ls="--", lw=0.8, label="true HR (75 bpm)")
    ax[2].set_ylim(40, 200)
    ax[2].set_xlabel("Time (s)")
    ax[2].set_ylabel("bpm")
    ax[2].legend()
    for a in ax:
        a.grid(True, alpha=0.3)
    fig.tight_layout()
    fig.savefig(out / "pipeline_demo.png", dpi=150)
    plt.close(fig)
    print(f"plots written to {out}/")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--header-only", action="store_true")
    ap.add_argument("--out", type=Path, default=Path("filter_design"))
    args = ap.parse_args()
    write_header(dsp.decimation_taps())
    if not args.header_only:
        plot_all(args.out)


if __name__ == "__main__":
    main()
